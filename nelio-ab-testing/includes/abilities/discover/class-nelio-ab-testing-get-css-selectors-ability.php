<?php
/**
 * Ability for discovering CSS selectors in a rendered page.
 *
 * @package Nelio_AB_Testing
 */

defined( 'ABSPATH' ) || exit;

/** Returns plugin-generated CSS selectors for a rendered page. */
class Nelio_AB_Testing_Get_Css_Selectors_Ability extends Nelio_AB_Testing_Ability {

	/**
	 * Registers the ability with WordPress.
	 *
	 * @return void
	 */
	public function register() {
		wp_register_ability(
			'nelio-ab-testing/get-css-selectors',
			array(
				'label'               => _x( 'Discover CSS selectors', 'text (ability name)', 'nelio-ab-testing' ),
				'description'         => 'Discovers selectors for editable elements in a rendered page. Use it before choosing a CSS test to verify that every requested element or content change can be implemented with an exact selector generated by the plugin for each target URL. If any required change has no matching selector, do not choose a CSS test for that change; consider a JavaScript or full content test instead. Use only an exact selector returned for the target URL; do not treat an ID, class, selector copied from inspected content, or selector that merely appears to match the page as valid on its own. When selector discovery for the requested URL is pending for the first time, ask the user to visit the provided URL and tell you when discovery is ready, then request the ability again with the same URL. If the user has already said that discovery for this URL is ready but the response is still pending, do not automatically repeat the request: ask whether they want to try selector discovery again or skip it.',
				'category'            => 'nelio-ab-testing',
				'input_schema'        => $this->object_schema(
					array(
						'url' => array(
							'type'        => 'string',
							'format'      => 'uri',
							'description' => 'URL of the page whose rendered editable elements should be inspected.',
						),
					),
					array( 'url' )
				),
				'output_schema'       => array(
					'type'                 => 'object',
					'properties'           => array(
						'status'       => array(
							'type'        => 'string',
							'enum'        => array( 'pending', 'ready' ),
							'description' => 'Whether selectors are still being generated or are ready to use.',
						),
						'url'          => array(
							'type'        => 'string',
							'format'      => 'uri',
							'description' => 'URL whose rendered editable elements were inspected.',
						),
						'message'      => array(
							'type'        => 'string',
							'description' => 'Explanation of what the agent should do next, when additional user action is required.',
						),
						'discoveryUrl' => array(
							'type'        => 'string',
							'format'      => 'uri',
							'description' => 'URL the user must visit when the requested page has not been processed yet.',
						),
						'selectors'    => array(
							'type'                 => 'object',
							'additionalProperties' => array(
								'type'                 => 'object',
								'properties'           => array(
									'outerHTML'   => array( 'type' => 'string' ),
									'allowedTags' => array(
										'type'  => 'array',
										'items' => array( 'type' => 'string' ),
									),
								),
								'required'             => array( 'outerHTML', 'allowedTags' ),
								'additionalProperties' => false,
							),
							'description'          => 'Map of plugin-generated CSS selectors to metadata for the corresponding editable element. A selector is valid only when its exact value appears as a key in this map for the requested URL. Use the listed allowed tags when creating HTML content for that selector.',
						),
					),
					'required'             => array( 'status', 'url' ),
					'additionalProperties' => false,
				),
				'permission_callback' => array( $this, 'permissions' ),
				'execute_callback'    => array( $this, 'execute' ),
				'meta'                => array(
					'show_in_rest' => false,
					'mcp'          => array(
						'public' => true,
						'type'   => 'tool',
						'server' => 'nelio-ab-testing',
					),
					'annotations'  => array(
						'readonly'    => false,
						'destructive' => false,
						'idempotent'  => false,
					),
				),
			)
		);
	}

	/**
	 * Checks whether the current user may discover CSS selectors.
	 *
	 * @param array<array-key,mixed> $input Input containing the target URL.
	 *
	 * @return true|WP_Error True when the user may discover selectors; otherwise, an error.
	 */
	public function permissions( $input ) {
		if ( ! is_user_logged_in() || ! nelioab()->is_ready() || ! current_user_can( 'edit_nab_experiments' ) ) {
			return new WP_Error( 'missing-capability', 'You cannot discover CSS selectors on this site.', array( 'status' => 403 ) );
		}
		return true;
	}

	/**
	 * Returns cached selectors or starts a browser-assisted discovery request.
	 *
	 * @param array<array-key,mixed> $input Input containing the URL to inspect.
	 *
	 * @return array<string,mixed>|WP_Error Selector-discovery status or an error.
	 */
	public function execute( $input ) {
		$allowed = $this->permissions( $input );
		if ( is_wp_error( $allowed ) ) {
			return $allowed;
		}

		$url    = is_string( $input['url'] ?? null ) ? $input['url'] : '';
		$record = Nelio_AB_Testing_Css_Selector_Discovery_Store::create_or_get( $url );
		if ( is_wp_error( $record ) ) {
			return $record;
		}

		$result = array(
			'status' => $record['status'],
			'url'    => $record['url'],
		);
		if ( 'pending' === $record['status'] ) {
			$result['discoveryUrl'] = add_query_arg( 'nab-css-selector-discovery', $record['token'], $record['url'] );
			$result['message']      = 'Selector discovery for this URL is still pending. If this is the first pending response, ask the user to visit the discovery URL and tell you when discovery is ready, then request the ability again with the same URL. If the user has already completed that step, ask whether they want to try again or skip the CSS test.';
		} else {
			$result['selectors'] = $record['selectors'];
		}
		return $this->bounded_response( $result );
	}
}
